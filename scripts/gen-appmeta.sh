#!/usr/bin/env bash
# 从 project.mk 生成 internal/appmeta/meta.go 的身份常量。
#
# 为什么是 shell 而不是本模块内的 Go 程序：meta.go 是被生成物。若生成器本身是本模块的
# Go 程序，一旦 meta.go 处于不可编译的中间态（正是 project init 改身份的那一瞬间），
# 生成器就跑不起来——自举死锁。shell 没有这个循环依赖，在 check-generator.sh 导出的
# 临时副本里同样可用。
#
# 安全前提：shell 拼 Go 字符串字面量本有转义风险，因此**校验先于生成**不是可选项——
# 两个字段先过严格正则（字符集内不含引号、反斜杠、换行、Make 元字符），拼接才是安全的。
#
# 用法：
#   gen-appmeta.sh            生成并写入 internal/appmeta/meta.go
#   gen-appmeta.sh --check    只校验生成物与提交物零差异，不落盘（供 make check 调用）
set -euo pipefail

# 用脚本自身位置定位项目根，**不能用 git**：gonew 的产物没有 .git，而"在刚 gonew 出来的
# 目录上跑 project init"正是本脚本的主用例（project init 会调用 make gen-appmeta）。
# 依赖 git 会让主用例直接失败。
repo_root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$repo_root"

project_mk="project.mk"
target="internal/appmeta/meta.go"

# read_kv 从 project.mk 读取一个赋值（形如 `KEY = value`），去掉首尾空白。
# 只认最后一次赋值，与 Make 的后赋值覆盖语义一致。
read_kv() {
  local key="$1"
  sed -n -E "s/^[[:space:]]*${key}[[:space:]]*=[[:space:]]*(.*)\$/\1/p" "$project_mk" \
    | sed -E 's/[[:space:]]+$//' | tail -n 1
}

[ -f "$project_mk" ] || { echo "[gen-appmeta] FAIL: 缺少 ${project_mk}（应用身份的唯一来源）" >&2; exit 1; }

app_name="$(read_kv APP_NAME)"
app_display_name="$(read_kv APP_DISPLAY_NAME)"

# 校验必须在写出任何内容之前完成：这两个值会分别进入 Make 表达式与 Go 字符串字面量，
# 未经校验即为 Make 表达式注入与字面量破坏面。
# APP_NAME 用 {0,62} 而非 {1,63}：后者会误拒合法的单字符名（如 x）。
if ! printf '%s' "$app_name" | grep -qE '^[a-z][a-z0-9_]{0,62}$'; then
  echo "[gen-appmeta] FAIL: APP_NAME 不合法（须匹配 ^[a-z][a-z0-9_]{0,62}\$）：${app_name:-<空>}" >&2
  exit 1
fi
if ! printf '%s' "$app_display_name" | grep -qE '^[A-Za-z0-9][A-Za-z0-9 ._-]{0,63}$'; then
  echo "[gen-appmeta] FAIL: APP_DISPLAY_NAME 不合法（须匹配 ^[A-Za-z0-9][A-Za-z0-9 ._-]{0,63}\$）：${app_display_name:-<空>}" >&2
  exit 1
fi

tmp="$(mktemp)"
# shellcheck disable=SC2064  # 有意在注册时展开 $tmp。
trap "rm -f '$tmp'" EXIT

cat > "$tmp" <<EOF
// Code generated by scripts/gen-appmeta.sh from project.mk. DO NOT EDIT.
//
// 应用身份的唯一来源是 project.mk。要改身份就改那里再跑 \`make gen-appmeta\`；
// 直接改本文件会被 \`make check\` 的 check-appmeta 拦下。

package appmeta

const (
	// CommandName 是对外暴露的命令名，取自 project.mk 的 APP_NAME。
	CommandName = "${app_name}"
	// RuntimeName 是运行时展示名称，取自 project.mk 的 APP_DISPLAY_NAME。
	RuntimeName = "${app_display_name}"
)
EOF

if [ "${1:-}" = "--check" ]; then
  # --strip-trailing-cr：本脚本按 LF 生成，而工作区的行尾取决于 checkout 时的
  # core.autocrlf。不忽略行尾的话，CRLF 工作区上每一次比对都报"整个文件不一致"，
  # 而门禁想守的是**身份是否漂移**——CommandName / RuntimeName 的取值，
  # 与行尾无关。报出来的 diff 还会是整文件，看不出哪个常量变了。
  #
  # 仓库已用 .gitattributes 把行尾固定为 LF，这里是对既有 clone 的兼容：
  # 那些工作区在执行一次 git add --renormalize 之前仍是 CRLF。
  if ! diff -u --strip-trailing-cr "$target" "$tmp" > /dev/null 2>&1; then
    echo "[gen-appmeta] FAIL: $target 与 $project_mk 的生成结果不一致，请运行 make gen-appmeta" >&2
    diff -u --strip-trailing-cr "$target" "$tmp" >&2 || true
    exit 1
  fi
  echo "check-appmeta OK: $target 与 $project_mk 一致"
  exit 0
fi

if [ "${1:-}" != "" ]; then
  echo "用法: $(basename "$0") [--check]" >&2
  exit 2
fi

mkdir -p "$(dirname "$target")"
cp "$tmp" "$target"
chmod 0644 "$target"
# 变量一律用花括号界定：紧跟其后的全角括号会被 bash 并入变量名，触发 set -u 报错。
echo "[gen-appmeta] 已生成 ${target}（APP_NAME=${app_name}）"
